// Existing upload/review/auth/idempotency regressions using the final pending contract.
import test from 'node:test';
import assert from 'node:assert/strict';
import {clubWorkflow,adminUser,enrollment} from './helpers/clubWorkflow.mjs';
import {uuid,parent,coach,teammate,outsider,player,otherPlayer,team} from './helpers/submissionDatabase.mjs';
const runtime=process.env.SDL004_PGLITE_RUNTIME;
test('proposal SQL: private roles, review conflicts, persistent uploads, lease recovery and session isolation',{skip:!runtime},async t=>{
 const {db,as,owner,upload,canRead}=await clubWorkflow(t,runtime);
 const allowed=async(who,fn)=>(await as(who,`SELECT public.${fn}('${player}') AS ok`))[0].ok;
 assert.equal(await allowed(parent,'sdl_004_submission_can_submit'),true);assert.equal(await allowed(outsider,'sdl_004_submission_can_submit'),false);
 assert.equal(await allowed(coach,'sdl_004_submission_can_submit'),false);
 await as(adminUser,`SELECT public.sdl_004_set_recording_permission('${enrollment}',true,'synthetic-permission')`);
 assert.equal(await allowed(coach,'sdl_004_submission_can_submit'),true);assert.equal(await allowed(parent,'sdl_004_submission_can_review'),false);
 await assert.rejects(as(parent,'SELECT * FROM public.sdl_video_submissions'),/permission denied/);
 const key=uuid(61),claim=uuid(62),fingerprint='a'.repeat(64);
 const reserve=`SELECT public.sdl_004_reserve_submission('${player}','${key}','${claim}','${fingerprint}',12,'pitching') AS r`;
 const r=(await as(parent,reserve))[0].r;assert.ok(r.id);assert.match(r.object_key,new RegExp(`pilot/${player}/`));
 await assert.rejects(as(parent,`SELECT public.sdl_004_finish_submission('${key}','${claim}','${parent}')`),/permission denied/);
 await db.exec('RESET ROLE;SET ROLE service_role');await db.query(`SELECT public.sdl_004_finish_submission('${key}','${claim}','${parent}')`);
 assert.equal(await canRead(r.id,parent),true);assert.equal(await canRead(r.id),false);
 await assert.rejects(as(parent,`SELECT public.sdl_004_review_submission('${r.id}','approved','forged')`),/Not authorized/);
 await as(coach,`SELECT public.sdl_004_review_submission('${r.id}','approved','Checked')`);
 await assert.rejects(as(coach,`SELECT public.sdl_004_review_submission('${r.id}','rejected','duplicate')`),e=>e.code==='PT409');
 const [item]=await as(parent,`SELECT * FROM public.sdl_004_list_submissions('${player}')`);assert.equal(item.status,'approved');assert.equal(item.history.length,2);
 const replay=(await as(parent,reserve))[0].r;assert.equal(replay.state,'complete');assert.equal(replay.id,r.id);
 await assert.rejects(as(parent,reserve.replace(fingerprint,'b'.repeat(64))),e=>e.code==='PT409');
 const pending=uuid(64);const query=`SELECT public.sdl_004_reserve_submission('${player}','${pending}','${claim}','${fingerprint}',12,'batting') AS r`;
 const original=(await as(parent,query))[0].r;
 await assert.rejects(as(parent,query.replace(claim,uuid(63))),e=>e.code==='PT409');
 await owner(`UPDATE public.sdl_submission_uploads SET lease_until=now()-interval '1 second' WHERE request_key='${pending}'`);
 const recovered=(await as(parent,query.replace(claim,uuid(63))))[0].r;assert.equal(recovered.id,original.id);
 await assert.rejects(as(parent,`SELECT public.sdl_004_reserve_submission('${otherPlayer}','${uuid(71)}','${claim}','${fingerprint}',12,'pitching')`),/Not authorized/);
 await owner(`DELETE FROM auth.sessions WHERE user_id='${parent}'`);assert.equal(await canRead(r.id,parent),false);
 await assert.rejects(as(parent,reserve),/Not authorized/);
});
