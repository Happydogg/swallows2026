// Optional local PostgreSQL/WASM check of the draft, never a Supabase connection.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {pilotDatabase,uuid,parent,coach,teammate,outsider,player,peer,otherPlayer,team,otherTeam,org,otherOrg,athlete,peerAthlete} from './helpers/submissionDatabase.mjs';
const runtime = process.env.SDL004_PGLITE_RUNTIME;

test('proposal SQL: local PostgreSQL role isolation, review history, consent and approved teammate access', { skip: !runtime }, async t => {
  const db=await pilotDatabase(t,runtime);
  const migration=fs.readdirSync(new URL('../supabase/migrations/',import.meta.url)).find(name=>name.endsWith('_sdl004_submission_workflows.sql'));
  await db.exec(fs.readFileSync(new URL('../supabase/migrations/'+migration,import.meta.url),'utf8'));
  async function as(id, sql) {
    await db.exec('RESET ROLE');
    await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)", [id ?? '']);
    await db.exec('SET ROLE authenticated');
    return (await db.query(sql)).rows;
  }
  const boolean = async (who, expression) => (await as(who, `SELECT ${expression} AS allowed`))[0].allowed;
  assert.equal(await boolean(parent, `public.sdl_004_submission_can_submit('${player}')`), true);
  assert.equal(await boolean(parent, `public.sdl_004_submission_can_submit('${otherPlayer}')`), false);
  assert.equal(await boolean(outsider, `public.sdl_004_submission_can_submit('${player}')`), false);
  assert.equal(await boolean(coach, `public.sdl_004_submission_can_review('${player}')`), true);
  assert.equal(await boolean(parent, `public.sdl_004_submission_can_review('${player}')`), false);
  assert.equal(await boolean(null, `public.sdl_004_submission_can_submit('${player}')`), false);
  await assert.rejects(as(parent, 'SELECT * FROM public.sdl_video_submissions'), /permission denied/);
  const key=uuid(61),claim=uuid(62),fingerprint='a'.repeat(64);
  const reservation=(await as(parent, `SELECT public.sdl_004_reserve_submission('${player}','${key}','${claim}','${fingerprint}',12,'pitching',true,ARRAY['${team}'::uuid]) AS r`))[0].r;
  const media=reservation.id;
  const record=`SELECT public.sdl_004_finish_submission('${key}','${claim}','${parent}')`;
  await assert.rejects(as(parent, record), /permission denied/);
  await db.exec('RESET ROLE; SET ROLE service_role'); await db.exec(record);
  assert.equal((await as(parent, `SELECT * FROM public.sdl_004_list_submissions('${player}')`))[0].status, 'pending');
  assert.equal(await boolean(teammate, `public.sdl_004_submission_can_read('${media}')`), false);
  assert.equal((await as(teammate, `SELECT * FROM public.sdl_004_clubhouse_videos('${team}')`)).length, 0);
  await assert.rejects(as(parent, `SELECT public.sdl_004_review_submission('${media}','approved','forged')`), /Not authorized/);
  await as(coach, `SELECT public.sdl_004_review_submission('${media}','approved','Checked')`);
  const reviewed = (await as(parent, `SELECT * FROM public.sdl_004_list_submissions('${player}')`))[0];
  assert.equal(reviewed.status, 'approved'); assert.equal(reviewed.history.length, 2);
  assert.equal(reviewed.history[1].actor, coach);
  await assert.rejects(as(coach, `SELECT public.sdl_004_review_submission('${media}','rejected','duplicate')`), /Already reviewed/);
  assert.equal(await boolean(teammate, `public.sdl_004_submission_can_read('${media}')`), true);
  const shared = await as(teammate, `SELECT * FROM public.sdl_004_clubhouse_videos('${team}')`);
  assert.equal(shared.length, 1); assert.equal(shared[0].history, undefined); assert.equal(shared[0].review_note, undefined);
  // Regression: the very same membership ID must not revive old consent.
  const captured=(await as(parent,`SELECT history FROM public.sdl_004_list_submissions('${player}')`))[0];
  assert.ok(captured);
  await db.exec('RESET ROLE');
  const originalMembership=(await db.query(`SELECT id FROM public.player_team_memberships WHERE player_id='${player}' AND team_id='${team}'`)).rows[0].id;
  await db.exec(`UPDATE public.player_team_memberships SET status='inactive' WHERE id='${originalMembership}'`);
  assert.equal(await boolean(teammate,`public.sdl_004_submission_can_read('${media}')`),false);
  await db.exec('RESET ROLE');await db.exec(`UPDATE public.player_team_memberships SET status='active' WHERE id='${originalMembership}'`);
  assert.equal(await boolean(teammate,`public.sdl_004_submission_can_read('${media}')`),false,'same-ID reactivation must require new guardian consent');
  await as(parent,`SELECT public.sdl_004_submission_consent('${media}',true,ARRAY['${team}'::uuid])`);
  assert.equal(await boolean(outsider, `public.sdl_004_submission_can_read('${media}')`), false);
  assert.equal((await as(teammate, `SELECT * FROM public.sdl_004_clubhouse_videos('${otherTeam}')`)).length, 0);
  await assert.rejects(as(coach, `SELECT public.sdl_004_submission_consent('${media}',true,ARRAY['${team}'::uuid])`), /Not authorized/);
  await as(parent, `SELECT public.sdl_004_submission_consent('${media}',false)`);
  assert.equal(await boolean(teammate, `public.sdl_004_submission_can_read('${media}')`), false);
  assert.equal((await as(teammate, `SELECT * FROM public.sdl_004_clubhouse_videos('${team}')`)).length, 0);
  await as(parent, `SELECT public.sdl_004_submission_consent('${media}',true,ARRAY['${team}'::uuid])`);
  const replay=(await as(parent, `SELECT public.sdl_004_reserve_submission('${player}','${key}','${uuid(63)}','${fingerprint}',12,'pitching',true,ARRAY['${team}'::uuid]) AS r`))[0].r;
  assert.equal(replay.state,'complete'); assert.equal(replay.id,media);
  await assert.rejects(as(parent, `SELECT public.sdl_004_reserve_submission('${player}','${key}','${uuid(63)}','${'b'.repeat(64)}',12,'pitching',true,ARRAY['${team}'::uuid])`), e=>e.code==='PT409');
  const pendingKey=uuid(64);
  await as(parent, `SELECT public.sdl_004_reserve_submission('${player}','${pendingKey}','${claim}','${fingerprint}',12,'batting',false)`);
  await assert.rejects(as(parent, `SELECT public.sdl_004_reserve_submission('${player}','${pendingKey}','${uuid(63)}','${fingerprint}',12,'batting',false)`), e=>e.code==='PT409');
  assert.equal((await as(coach, `SELECT * FROM public.sdl_004_review_queue('${otherTeam}','all')`)).length,0);
  await db.exec('RESET ROLE'); await db.exec(`UPDATE public.organizations SET status='suspended' WHERE id='${org}'`);
  assert.equal(await boolean(coach, `public.sdl_004_submission_can_review('${player}')`),false);
  await db.exec('RESET ROLE'); await db.exec(`UPDATE public.organizations SET status='active' WHERE id='${org}'`);
  await db.exec(`DELETE FROM auth.sessions WHERE user_id='${teammate}'`);
  assert.equal(await boolean(teammate, `public.sdl_004_submission_can_read('${media}')`),false);
  await db.exec('RESET ROLE'); await db.exec(`INSERT INTO auth.sessions VALUES('${teammate}','${teammate}',null)`);
  // Team transfers and rejoining with a new membership never inherit old consent.
  const alternateTeam=uuid(23);
  await db.exec('RESET ROLE');
  await db.exec(`INSERT INTO public.teams(id,organization_id,status) VALUES('${alternateTeam}','${org}','active');
   INSERT INTO public.team_memberships VALUES('${alternateTeam}','${teammate}','active','parent');
   INSERT INTO public.player_team_memberships(player_id,team_id,organization_id,status,end_date) VALUES('${peer}','${alternateTeam}','${org}','active',null);
   UPDATE public.player_team_memberships SET status='inactive' WHERE player_id='${player}';
   INSERT INTO public.player_team_memberships(player_id,team_id,organization_id,status,end_date) VALUES('${player}','${alternateTeam}','${org}','active',null);`);
  assert.equal(await boolean(teammate,`public.sdl_004_submission_can_read('${media}')`),false);
  await db.exec('RESET ROLE');await db.exec(`INSERT INTO public.player_team_memberships(player_id,team_id,organization_id,status,end_date) VALUES('${player}','${team}','${org}','active',null)`);
  assert.equal(await boolean(teammate,`public.sdl_004_submission_can_read('${media}')`),false);
  await as(parent,`SELECT public.sdl_004_submission_consent('${media}',true,ARRAY['${team}'::uuid])`);
  assert.equal(await boolean(teammate,`public.sdl_004_submission_can_read('${media}')`),true);
  const coachKey=uuid(71),coachClaim=uuid(72);
  const self=(await as(coach,`SELECT public.sdl_004_reserve_submission('${player}','${coachKey}','${coachClaim}','${fingerprint}',12,'throwing',false) AS r`))[0].r;
  await db.exec('RESET ROLE; SET ROLE service_role');await db.exec(`SELECT public.sdl_004_finish_submission('${coachKey}','${coachClaim}','${coach}')`);
  await assert.rejects(as(coach,`SELECT public.sdl_004_review_submission('${self.id}','approved','self')`),e=>e.code==='42501');
  // Lease recovery retains the same server media ID, without creating duplicates.
  await db.exec('RESET ROLE');await db.exec(`UPDATE public.sdl_submission_uploads SET lease_until=now()-interval '1 second' WHERE request_key='${pendingKey}'`);
  const recovered=(await as(parent,`SELECT public.sdl_004_reserve_submission('${player}','${pendingKey}','${uuid(73)}','${fingerprint}',12,'batting',false) AS r`))[0].r;
  assert.equal(recovered.state,'reserved');
  await db.exec('RESET ROLE'); await db.exec(`UPDATE public.athlete_guardians SET status='revoked' WHERE user_id='${parent}'`);
  assert.equal(await boolean(parent, `public.sdl_004_submission_can_submit('${player}')`), false);
  assert.equal(await boolean(teammate, `public.sdl_004_submission_can_read('${media}')`), false);
  // Revoked parent sharing must disappear even to the coach listing Clubhouse.
  assert.equal((await as(coach, `SELECT * FROM public.sdl_004_clubhouse_videos('${team}')`)).length, 0);
  await db.exec('RESET ROLE'); await db.exec(`UPDATE public.profiles SET status='suspended' WHERE id='${coach}'`);
  assert.equal(await boolean(coach, `public.sdl_004_submission_can_review('${player}')`), false);
});
